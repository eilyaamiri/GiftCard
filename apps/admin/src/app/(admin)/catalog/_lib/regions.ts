/**
 * Other spellings of a region that already has a code in the list (`GB` is
 * `UK`, `GLOBAL` is `WW`). A SKU that carries one still shows its name, but the
 * picker offers only the one code, so one region is never two entries.
 */
const ALIASES: ReadonlySet<string> = new Set(["WORLDWIDE", "WW", "INT", "INTERNATIONAL", "EUROPE", "USA", "UK", "TURKEY"]);

/** The Persian name for a region code, or null when the list has none for it (or there is no region). */
export function regionName(region: string | null | undefined): string | null {
  const code = region?.trim().toUpperCase();
  return code === undefined || code === "" ? null : (REGION_NAMES[code] ?? null);
}

/** «آمریکا (US)» for a known region, the bare code for one the list does not know. */
export function regionDisplay(region: string): string {
  const name = regionName(region);
  return name === null ? region : `${name} (${region.toUpperCase()})`;
}

export interface RegionOption {
  readonly code: string;
  readonly name: string;
}

/** Every region the picker offers, in Persian alphabetical order, aliases left out. */
export function regionOptions(): readonly RegionOption[] {
  const collator = new Intl.Collator("fa");
  return Object.entries(REGION_NAMES)
    .filter(([code]) => !ALIASES.has(code))
    .map(([code, name]) => ({ code, name }))
    .sort((a, b) => collator.compare(a.name, b.name));
}
