/**
 * The Persian name for a region code, or the code itself when we have no name
 * for it. `null` only when there is no region at all.
 */
export function regionLabel(region: string | null | undefined): string | null {
  const code = region?.trim();
  if (code === undefined || code === "") return null;
  return NAMES[code.toUpperCase()] ?? code;
}

/**
 * Whether `query` names the region — by its code (`us`) or by any part of its
 * Persian name (`آمر`). Used by the catalog's region search, which would
 * otherwise only answer to codes nobody types in Persian.
 */
export function regionMatches(region: string, query: string): boolean {
  const needle = query.trim().toLowerCase();
  if (needle === "") return true;
  return (
    region.toLowerCase().includes(needle) ||
    (regionLabel(region) ?? "").toLowerCase().includes(needle)
  );
}

/**
 * Regions ordered by their Persian name, so a customer scanning a list of 158
 * finds «ترکیه» where the alphabet says it is rather than under `TR`. Codes with
 * no name sort by the code, after the named ones.
 */
export function sortRegions(regions: readonly string[]): string[] {
  const collator = new Intl.Collator("fa");
  return [...regions].sort((a, b) => {
    const named = Number(NAMES[b.toUpperCase()] !== undefined) - Number(NAMES[a.toUpperCase()] !== undefined);
    if (named !== 0) return named;
    return collator.compare(regionLabel(a) ?? a, regionLabel(b) ?? b);
  });
}
